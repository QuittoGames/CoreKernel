#pragma once

typedef enum COLORS {
    BLACK        = 0x0, // 0000
    BLUE         = 0x1, // 0001
    GREEN        = 0x2, // 0010
    CYAN         = 0x3, // 0011
    RED          = 0x4, // 0100
    MAGENTA      = 0x5, // 0101
    BROWN        = 0x6, // 0110
    LIGHT_GRAY   = 0x7, // 0111 (padrão)
    DARK_GRAY    = 0x8, // 1000
    LIGHT_BLUE   = 0x9, // 1001
    LIGHT_GREEN  = 0xA, // 1010
    LIGHT_CYAN   = 0xB, // 1011
    LIGHT_RED    = 0xC, // 1100
    LIGHT_MAGENTA= 0xD, // 1101
    YELLOW       = 0xE, // 1110
    WHITE        = 0xF  // 1111
} COLORS;
